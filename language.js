    /* =====================================================
       TRANSLATE TEXT
    ====================================================== */

    function translate(root, language) {

        const map =
            language === "ar"
                ? AR
                : EN;


        /*
         * Translate regular text nodes
         */

        const walker =
            document.createTreeWalker(
                root,
                NodeFilter.SHOW_TEXT
            );


        const nodes = [];

        while (walker.nextNode()) {

            nodes.push(
                walker.currentNode
            );
        }


        nodes.forEach(node => {

            const original =
                node.nodeValue.trim();

            if (!original) {
                return;
            }


            if (map[original]) {

                node.nodeValue =
                    node.nodeValue.replace(
                        original,
                        map[original]
                    );
            }

        });


        /*
         * Translate placeholders
         */

        root
            .querySelectorAll(
                "[data-i18n-placeholder]"
            )
            .forEach(element => {

                const key =
                    element.getAttribute(
                        "data-i18n-placeholder"
                    );

                if (map[key]) {

                    element.placeholder =
                        map[key];
                }
            });


        /*
         * Also support old placeholder system
         */

        root
            .querySelectorAll(
                "input, textarea"
            )
            .forEach(element => {

                const placeholder =
                    element.placeholder;

                if (
                    placeholder &&
                    map[placeholder]
                ) {

                    element.placeholder =
                        map[placeholder];
                }
            });


        /*
         * Translate select options
         */

        root
            .querySelectorAll("option")
            .forEach(option => {

                const text =
                    option.textContent.trim();

                if (map[text]) {

                    option.textContent =
                        map[text];
                }
            });


        /*
         * Translate document title
         */

        const title =
            document.title.trim();

        if (map[title]) {

            document.title =
                map[title];
        }
    }


    /* =====================================================
       APPLY LANGUAGE
    ====================================================== */

    function apply(language) {

        /*
         * Safety check
         */

        if (
            language !== "ar" &&
            language !== "en"
        ) {

            language = "en";
        }


        const root =
            document.body;


        /*
         * RTL / LTR
         */

        root.classList.toggle(
            "rtl",
            language === "ar"
        );


        document.documentElement.lang =
            language;


        document.documentElement.dir =
            language === "ar"
                ? "rtl"
                : "ltr";


        /*
         * Translate page
         */

        translate(
            root,
            language
        );


        /*
         * Save language
         */

        localStorage.setItem(
            "bingo-lang",
            language
        );


        /*
         * Change logo
         */

        updateLogo(language);


        /*
         * Change language button
         */

        const switchButton =
            document.getElementById(
                "langSwitch"
            );


        if (switchButton) {

            switchButton.textContent =
                language === "ar"
                    ? "EN"
                    : "العربية";

            switchButton.setAttribute(
                "aria-label",
                language === "ar"
                    ? "Switch to English"
                    : "التبديل إلى العربية"
            );
        }
    }


    /* =====================================================
       ADD LANGUAGE BUTTON
    ====================================================== */

    function addSwitch() {

        const actions =
            document.querySelector(
                ".actions"
            );


        /*
         * Don't add twice
         */

        if (
            !actions ||
            document.getElementById(
                "langSwitch"
            )
        ) {
            return;
        }


        const button =
            document.createElement(
                "button"
            );


        button.id =
            "langSwitch";


        button.className =
            "lang-switch";


        button.type =
            "button";


        /*
         * Initial text
         */

        const currentLanguage =
            localStorage.getItem(
                "bingo-lang"
            ) || "en";


        button.textContent =
            currentLanguage === "ar"
                ? "EN"
                : "العربية";


        /*
         * Click
         */

        button.addEventListener(
            "click",
            function () {

                const current =
                    localStorage.getItem(
                        "bingo-lang"
                    ) || "en";


                const next =
                    current === "ar"
                        ? "en"
                        : "ar";


                apply(next);
            }
        );


        /*
         * Put button before Login
         */

        actions.insertBefore(
            button,
            actions.firstChild
        );
    }


    /* =====================================================
       3D EFFECTS
    ====================================================== */

    function init3D() {

        const reduceMotion =
            window.matchMedia &&
            window.matchMedia(
                "(prefers-reduced-motion: reduce)"
            ).matches;


        if (reduceMotion) {
            return;
        }


        /*
         * Card tilt
         */

        document
            .querySelectorAll(
                ".card, .feature, .stat"
            )
            .forEach(element => {

                element.classList.add(
                    "js-tilt"
                );


                element.addEventListener(
                    "pointermove",
                    function (event) {

                        const rect =
                            element.getBoundingClientRect();


                        const x =
                            (event.clientX -
                                rect.left) /
                                rect.width -
                            0.5;


                        const y =
                            (event.clientY -
                                rect.top) /
                                rect.height -
                            0.5;


                        element.style.transform =
                            `perspective(850px)
                             rotateX(${(-y * 4).toFixed(2)}deg)
                             rotateY(${(x * 5).toFixed(2)}deg)
                             translateY(-3px)`;
                    }
                );


                element.addEventListener(
                    "pointerleave",
                    function () {

                        element.style.transform =
                            "";
                    }
                );

            });


        /*
         * Main 3D scene
         */

        const scene =
            document.getElementById(
                "scene3d"
            );


        if (!scene) {
            return;
        }


        const cube =
            scene.querySelector(
                ".cube3d"
            );


        /*
         * Mouse movement
         */

        scene.addEventListener(
            "pointermove",
            function (event) {

                const rect =
                    scene.getBoundingClientRect();


                const x =
                    (event.clientX -
                        rect.left) /
                        rect.width -
                    0.5;


                const y =
                    (event.clientY -
                        rect.top) /
                        rect.height -
                    0.5;


                scene.style.transform =
                    `rotateX(${(-y * 4).toFixed(2)}deg)
                     rotateY(${(x * 5).toFixed(2)}deg)`;


                if (cube) {

                    cube.style.transform =
                        `rotateX(${(-16 - y * 10).toFixed(2)}deg)
                         rotateY(${(-28 + x * 18).toFixed(2)}deg)
                         rotateZ(${(x * 3).toFixed(2)}deg)`;
                }

            }
        );


        /*
         * Mouse leaves scene
         */

        scene.addEventListener(
            "pointerleave",
            function () {

                scene.style.transform =
                    "";


                if (cube) {

                    cube.style.transform =
                        "rotateX(-16deg) rotateY(-28deg) rotateZ(2deg)";
                }
            }
        );
    }


    /* =====================================================
       SEARCH
    ====================================================== */

    window.searchMarketplace =
        function () {

            const input =
                document.getElementById("q");

            const location =
                document.getElementById(
                    "location"
                );


            const query =
                input
                    ? input.value.trim()
                    : "";


            const city =
                location
                    ? location.value
                    : "";


            const params =
                new URLSearchParams();


            if (query) {

                params.set(
                    "q",
                    query
                );
            }


            if (city) {

                params.set(
                    "city",
                    city
                );
            }


            let url =
                "marketplace.html";


            const queryString =
                params.toString();


            if (queryString) {

                url +=
                    "?" + queryString;
            }


            window.location.href =
                url;
        };


